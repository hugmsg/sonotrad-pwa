-- Stock Pidem : tables et fonctions (remplacent le classeur « Sonotrad - Catalogue »).
-- Appelées uniquement par Apps Script (clé secrète) ; réponses identiques aux anciennes actions stock_*.
-- Stock d'une réf = dernier inventaire + entrées − sorties qui le suivent (ordre : date puis id).

CREATE TABLE public.stock_articles (
  ref          text PRIMARY KEY CHECK (btrim(ref) <> ''),
  description  text NOT NULL DEFAULT '',
  famille      text NOT NULL DEFAULT '',
  fournisseur  text NOT NULL DEFAULT '',
  ref_fourn    text NOT NULL DEFAULT '',
  prix_ht      numeric,
  seuil        numeric CHECK (seuil >= 0),
  actif        boolean NOT NULL DEFAULT true,
  date_import  date,
  date_modif   date,
  ordre        bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE
);

CREATE TABLE public.stock_mouvements (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  date         timestamptz NOT NULL DEFAULT now(),
  ref          text NOT NULL CHECK (btrim(ref) <> ''),
  type         text NOT NULL CHECK (type IN ('entrée', 'sortie', 'inventaire')),
  quantite     numeric NOT NULL,
  utilisateur  text NOT NULL DEFAULT '',
  note         text NOT NULL DEFAULT '',
  operation    uuid
);
CREATE INDEX stock_mouvements_ref_date ON public.stock_mouvements (ref, date, id);
CREATE INDEX stock_mouvements_date ON public.stock_mouvements (date DESC, id DESC);

CREATE TABLE public.stock_mouvements_supprimes (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mouvement    jsonb NOT NULL,
  supprime_le  timestamptz NOT NULL DEFAULT now(),
  supprime_par text NOT NULL DEFAULT ''
);

CREATE TABLE public.stock_favoris (
  ref          text PRIMARY KEY,
  ordre        bigint GENERATED BY DEFAULT AS IDENTITY
);

CREATE TABLE public.stock_lv_liens (
  op_key       text PRIMARY KEY,
  numero       text NOT NULL,
  display      text NOT NULL,
  date         timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.stock_articles             ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.stock_mouvements           ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.stock_mouvements_supprimes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.stock_favoris              ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.stock_lv_liens             ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.stock_articles, public.stock_mouvements, public.stock_mouvements_supprimes,
              public.stock_favoris, public.stock_lv_liens FROM PUBLIC, anon, authenticated;

-- ── Outils ──────────────────────────────────────────────────────────────────

-- Date au format JavaScript toISOString() (les clés d'opération de la PWA en dépendent).
CREATE FUNCTION public._stock_iso(d timestamptz)
 RETURNS text
 LANGUAGE sql
 IMMUTABLE
 SET search_path TO 'public'
AS $function$
  SELECT to_char(d AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"');
$function$;

-- Nombre lu depuis du JSON comme Number() en JavaScript (illisible → 0).
CREATE FUNCTION public._stock_nombre(v jsonb)
 RETURNS numeric
 LANGUAGE sql
 IMMUTABLE
 SET search_path TO 'public'
AS $function$
  SELECT CASE
    WHEN jsonb_typeof(v) = 'number' THEN (v #>> '{}')::numeric
    WHEN jsonb_typeof(v) = 'string' AND btrim(v #>> '{}') ~ '^-?[0-9]+(\.[0-9]+)?$' THEN btrim(v #>> '{}')::numeric
    WHEN jsonb_typeof(v) = 'string' AND btrim(v #>> '{}') = '' THEN 0
    ELSE 0 END;
$function$;

-- Par réf ayant au moins un mouvement : quantité du dernier inventaire, delta qui le suit, date du dernier mouvement.
CREATE FUNCTION public._stock_etat()
 RETURNS TABLE(ref text, inv_qty numeric, delta numeric, derniere_date timestamptz)
 LANGUAGE sql
 STABLE
 SET search_path TO 'public'
AS $function$
  WITH inv AS (
    SELECT DISTINCT ON (m.ref) m.ref, m.date, m.id, m.quantite
      FROM stock_mouvements m WHERE m.type = 'inventaire'
     ORDER BY m.ref, m.date DESC, m.id DESC
  )
  SELECT m.ref,
         max(inv.quantite),
         coalesce(sum(CASE WHEN inv.ref IS NULL OR (m.date, m.id) > (inv.date, inv.id)
                           THEN CASE m.type WHEN 'entrée' THEN m.quantite WHEN 'sortie' THEN -m.quantite ELSE 0 END
                           ELSE 0 END), 0),
         max(m.date)
    FROM stock_mouvements m LEFT JOIN inv ON inv.ref = m.ref
   GROUP BY m.ref;
$function$;

CREATE FUNCTION public._stock_mouvement_json(m stock_mouvements)
 RETURNS jsonb
 LANGUAGE sql
 STABLE
 SET search_path TO 'public'
AS $function$
  SELECT jsonb_build_object('date', _stock_iso(m.date), 'ref', m.ref, 'type', m.type,
                            'qty', m.quantite, 'user', m.utilisateur, 'note', m.note);
$function$;

