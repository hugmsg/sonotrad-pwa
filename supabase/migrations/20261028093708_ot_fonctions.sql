-- Fiches d'opérations (OT) : fonctions serveur (appelées uniquement par Apps Script, clé secrète).
-- Calcul repris de la matrice Excel (contrôlé sur 413/425 OT 2026) :
--   lignes hors sanitaire : MO = quantité × MO unitaire (plafonnée si mo_plafond), ou montant saisi ;
--   bloc sanitaire : somme quantité × prix pièce → « Main d'œuvre pièces » (SON-0100)
--                    = arrondi au 0,5 de (somme + 0,5) × majoration_pieces ;
--   ligne sans quantité = rappel, ne compte pas. Total HT = MO des lignes + MO pièces.
-- À la validation, les prix unitaires sont figés sur chaque ligne : un changement de tarif
-- ne modifie jamais une fiche validée.

ALTER TABLE public.ot_lignes ADD COLUMN mo_unitaire numeric;
ALTER TABLE public.ot_lignes ADD COLUMN prix_piece_unitaire numeric;

-- 1 = essai (numéros « ESSAI-AAMMJJ-NNNN », la matrice Excel garde le vrai compteur).
INSERT INTO public.ot_parametres (cle, valeur, libelle)
VALUES ('essai', 1, 'Fiches en essai : numéro ESSAI-…, aucune sortie de stock (1 = oui, 0 = non)');

CREATE TABLE public.ot_tarifs_journal (
  id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  le      timestamptz NOT NULL DEFAULT now(),
  par     text NOT NULL DEFAULT '',
  type    text NOT NULL CHECK (type IN ('reference', 'forfait', 'parametre')),
  cle     text NOT NULL,
  avant   jsonb,
  apres   jsonb
);
ALTER TABLE public.ot_tarifs_journal ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.ot_tarifs_journal FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.ot_tarifs_journal_id_seq FROM PUBLIC, anon, authenticated;

