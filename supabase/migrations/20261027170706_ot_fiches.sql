-- Fiches d'opérations (OT) : une fiche par intervention sur un module, ses lignes.
-- Lues et écrites uniquement côté serveur (clé secrète), comme le stock.

-- Montant maximum de main-d'œuvre par ligne (ex. laine de verre : 40 €/u, 200 € au plus).
ALTER TABLE public.ot_references ADD COLUMN mo_plafond numeric CHECK (mo_plafond >= 0);
UPDATE public.ot_references SET mo_plafond = 200 WHERE ref = 'SON-0082';

CREATE TABLE public.ot_fiches (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code_planning  text NOT NULL CHECK (btrim(code_planning) <> ''),
  numero_module  text NOT NULL DEFAULT '',
  agence         text NOT NULL DEFAULT '',
  type_module    text NOT NULL DEFAULT '',
  commentaire    text NOT NULL DEFAULT '',
  numero_ot      text UNIQUE,
  statut         text NOT NULL DEFAULT 'brouillon'
                 CHECK (statut IN ('brouillon', 'a_valider', 'validee', 'envoyee', 'annulee')),
  notes          text NOT NULL DEFAULT '',
  total_ht       numeric,
  saisi_par      text NOT NULL DEFAULT '',
  cree_le        timestamptz NOT NULL DEFAULT now(),
  modifie_le     timestamptz NOT NULL DEFAULT now(),
  valide_par     text,
  valide_le      timestamptz,
  envoye_le      timestamptz
);
CREATE INDEX ot_fiches_code_planning ON public.ot_fiches (code_planning);
CREATE INDEX ot_fiches_statut ON public.ot_fiches (statut, cree_le DESC);

-- quantite NULL = ligne présente sans quantité (rappel), absente des documents.
-- mo_saisi / prix_piece_saisi : montant tapé à la main, prioritaire sur le tarif.
-- origine : atelier (saisie d'Anaïs), office (toujours proposée), prevu (historique / demande client,
-- à confirmer par une quantité), bureau (ajoutée au contrôle).
CREATE TABLE public.ot_lignes (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fiche_id          bigint NOT NULL REFERENCES public.ot_fiches (id) ON DELETE CASCADE,
  ordre             integer NOT NULL DEFAULT 0,
  bloc              text NOT NULL CHECK (bloc IN ('pieces', 'sanitaire', 'diverses', 'travaux')),
  ref               text,
  libelle           text NOT NULL DEFAULT '',
  quantite          numeric CHECK (quantite >= 0),
  unite             text NOT NULL DEFAULT 'u',
  occasion          boolean NOT NULL DEFAULT false,
  mo_saisi          numeric,
  prix_piece_saisi  numeric,
  origine           text NOT NULL DEFAULT 'atelier' CHECK (origine IN ('atelier', 'office', 'prevu', 'bureau'))
);
CREATE INDEX ot_lignes_fiche ON public.ot_lignes (fiche_id, ordre, id);

ALTER TABLE public.ot_fiches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ot_lignes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.ot_fiches, public.ot_lignes FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.ot_fiches_id_seq, public.ot_lignes_id_seq FROM PUBLIC, anon, authenticated;
